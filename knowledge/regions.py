# ЕДИНЫЙ РЕЗОЛВЕР РЕГИОНА
# =============================================================================
class RegionResolver:
    """
    Единый резолвер региона для всех модулей TENDER-BOT.

    Используется:
      - detailed_parser.py — парсинг из common-info (адрес заказчика)
      - address_parser.py — подсчёт регионов в адресах поставки
      - search/parser.py — fallback из поисковой выдачи
    """

    @staticmethod
    def extract_region(address: str) -> str:
        """
        Извлекает регион из адресной строки (полный парсинг).
        Используется в detailed_parser.py для common-info.
        """
        if not address:
            return ""

        # Убираем почтовый индекс
        address = re.sub(r"^\d{6},?\s*", "", address)
        address_lower = address.lower()

        # 1. Прямое совпадение с полным названием региона
        for region in RUSSIAN_REGIONS:
            if region.lower() in address_lower:
                return region

        # 2. По городу (fallback)
        city_match = re.search(r"г\.?\s*([А-Яа-я\-]+)", address, re.IGNORECASE)
        if city_match:
            city = city_match.group(1).lower().strip()
            if city in CITY_TO_REGION:
                return CITY_TO_REGION[city]

        # 3. По частям адреса (через запятую)
        parts = [p.strip() for p in address.split(",")]
        for part in parts:
            part_lower = part.lower()
            for region in RUSSIAN_REGIONS:
                if region.lower() in part_lower:
                    return region
            # Сокращённые формы
            if "янао" in part_lower or "ямало-ненец" in part_lower:
                return "Ямало-Ненецкий автономный округ"
            if "хмао" in part_lower or "ханты-манс" in part_lower:
                return "Ханты-Мансийский автономный округ"
            if "чукот" in part_lower:
                return "Чукотский автономный округ"
            if "ненец" in part_lower and "ямал" not in part_lower:
                return "Ненецкий автономный округ"

        return ""

    @staticmethod
    def resolve_from_city(city: str) -> str:
        """Определяет регион по названию города."""
        if not city:
            return ""
        return CITY_TO_REGION.get(city.lower().strip(), "")

    @staticmethod
    def resolve_from_search_text(text: str) -> Optional[str]:
        """
        Быстрый regex-поиск для поисковой выдачи.
        Использует SEARCH_REGION_PATTERNS (упрощённые паттерны).
        """
        if not text:
            return None

        text_lower = text.lower()
        for pattern, region_name in SEARCH_REGION_PATTERNS.items():
            if re.search(pattern, text_lower, re.IGNORECASE):
                return region_name

        return None

    @staticmethod
    def is_region_match(text: str, region: str) -> bool:
        """Проверяет, входит ли регион в текст."""
        if not text or not region:
            return False
        return region.lower() in text.lower()
